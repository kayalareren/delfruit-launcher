const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('launcher', {
  site: () => ipcRenderer.invoke('app:site'),
  version: () => ipcRenderer.invoke('app:version'),
  windowFocused: () => ipcRenderer.invoke('app:window-focused'),
  pointerVisible: (visible) => ipcRenderer.send('app:pointer-visible', visible),
  launchOptions: () => ipcRenderer.invoke('settings:launch-options'),
  setLaunchOption: (key, value) => ipcRenderer.invoke('settings:set-launch-option', key, value),
  getLanguage: () => ipcRenderer.invoke('app:get-language'),
  setLanguage: (language) => ipcRenderer.invoke('app:set-language', language),
  getFolders: () => ipcRenderer.invoke('settings:folders'),
  controls: () => ipcRenderer.invoke('settings:controls'),
  saveControls: (bindings, gamepad) => ipcRenderer.invoke('settings:save-controls', bindings, gamepad),
  setControlsEnabled: (enabled) => ipcRenderer.invoke('settings:set-controls-enabled', enabled),
  gameAudio: () => ipcRenderer.invoke('settings:game-audio'),
  saveGameAudio: (value) => ipcRenderer.invoke('settings:save-game-audio', value),
  chooseAudioConfig: (id, clear) => ipcRenderer.invoke('library:audio-config', id, clear),
  getTheme: () => ipcRenderer.invoke('settings:get-theme'),
  setTheme: (theme) => ipcRenderer.invoke('settings:set-theme', theme),
  getRememberLogin: () => ipcRenderer.invoke('settings:get-remember-login'),
  setRememberLogin: (value) => ipcRenderer.invoke('settings:set-remember-login', value),
  getLayout: () => ipcRenderer.invoke('settings:get-layout'),
  setLayout: (value) => ipcRenderer.invoke('settings:set-layout', value),
  getCardFields: () => ipcRenderer.invoke('settings:get-card-fields'),
  setCardField: (field, visible) => ipcRenderer.invoke('settings:set-card-field', field, visible),
  exportProfile: (id) => ipcRenderer.invoke('profiles:export', id),
  importProfile: (id) => ipcRenderer.invoke('profiles:import', id),
  profiles: () => ipcRenderer.invoke('profiles:list'),
  createProfile: (name) => ipcRenderer.invoke('profiles:create', name),
  selectProfile: (id) => ipcRenderer.invoke('profiles:select', id),
  resetProfile: (id) => ipcRenderer.invoke('profiles:reset-data', id),
  chooseFolder: (key) => ipcRenderer.invoke('settings:choose-folder', key),
  complete: (id, completed) => ipcRenderer.invoke('library:complete', id, completed),
  favorite: (id, favorite) => ipcRenderer.invoke('library:favorite', id, favorite),
  personalRating: (id, rating) => ipcRenderer.invoke('library:personal-rating', id, rating),
  listCollections: () => ipcRenderer.invoke('collections:list'),
  createCollection: (name) => ipcRenderer.invoke('collections:create', name),
  setMembership: (gameId, collectionId, checked) =>
    ipcRenderer.invoke('collections:membership', gameId, collectionId, checked),
  openBrowser: (url) => ipcRenderer.invoke('app:open-browser', url),
  list: () => ipcRenderer.invoke('library:list'),
  refreshMetadata: () => ipcRenderer.invoke('library:refresh-metadata'),
  setSource: (id, page) => ipcRenderer.invoke('library:set-source', id, page),
  installFile: () => ipcRenderer.invoke('library:install-file'),
  importFolder: () => ipcRenderer.invoke('library:import-folder'),
  customCover: (id, clear) => ipcRenderer.invoke('library:custom-cover', id, clear),
  launch: (id) => ipcRenderer.invoke('library:launch', id),
  remove: (id) => ipcRenderer.invoke('library:remove', id),
  show: (id) => ipcRenderer.invoke('library:show', id),
  on: (channel, callback) => {
    const allowed = ['download-started', 'download-progress', 'download-finished', 'library-changed', 'focus-navigation', 'game-audio-unavailable', 'window-focus', 'browser-pointer-key', 'browser-arrow-state'];
    if (allowed.includes(channel)) ipcRenderer.on(channel, (_event, value) => callback(value));
  }
});
